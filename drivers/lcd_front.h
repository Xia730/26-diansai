/**
 * @brief  根据字符查找对应的字模数据
 * @param  c 字符
 * @return 指向5字节字模数据的指针
 */
static inline const uint8_t *lcd_get_glyph(char c)
{
    if (c >= 'a' && c <= 'z') {
        return font5x7_lower[(uint8_t)(c - 'a')];
    }

    /* 非打印字符或超出范围则替换为空格 */
    if (c < 32 || c > 95) {
        c = ' ';
    }

    return font5x7[(uint8_t)c - 32];
}

